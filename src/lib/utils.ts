import { clsx, type ClassValue } from "clsx"
import { twMerge } from "tailwind-merge"

export function cn(...inputs: ClassValue[]) {
  return twMerge(clsx(inputs))
}

// Render a yyyy-mm-dd date the way a UK reader expects: "7 Aug 2026".
export function formatDateUK(isoDate: string): string {
  const d = new Date(`${isoDate}T00:00:00Z`);
  if (Number.isNaN(d.getTime())) return isoDate;
  return d.toLocaleDateString("en-GB", {
    day: "numeric",
    month: "short",
    year: "numeric",
    timeZone: "UTC",
  });
}

const UUID_RE =
  /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i;

// Guard ids from forms/URLs before they reach a Postgres uuid cast, which
// would otherwise throw (a 500) instead of a clean redirect/404.
export function isUuid(value: string): boolean {
  return UUID_RE.test(value);
}
